import { readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { describe, expect, it } from "vitest";
import { parseExpectation } from "../../scripts/conformance/expectation.mts";
import { readTarget } from "../../scripts/conformance/target.mts";
import { buildExamples, renderCatalog } from "../../scripts/examples-sync.mts";
import { EXAMPLE_CONFIGS } from "@/features/playground/examples/examples.config";
import { EXAMPLES, exampleForSource } from "@/features/playground/examples";
import { SIMULATOR } from "./support/simulator";

// The playground's example catalog is generated from recorded fixtures (scripts/examples-sync.mts),
// so an example can never drift from, or claim a "Matches Node" badge it did not earn against, what
// real Node printed.

const CONFORMANCE_ROOT = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = join(CONFORMANCE_ROOT, "..", "..");

const TITLES = [
  "Promise vs setTimeout",
  "nextTick vs Promise",
  "async/await ordering",
  "await a thenable (the 2 extra ticks)",
  "setTimeout 0 vs setImmediate (nondeterministic!)",
  "hidden classes: same shape vs different order",
  "elements kinds: SMI → DOUBLE → HOLEY",
  "closure context",
  "recursive factorial",
  "uncaught TypeError",
];

const recorded = (fixture: string) =>
  parseExpectation(JSON.parse(readFileSync(join(CONFORMANCE_ROOT, "fixtures", `${fixture}.expected.json`), "utf8")));

describe("example catalog", () => {
  it("lists the ten §8.3 examples, verbatim and in order", () => {
    expect(EXAMPLES.map((e) => e.title)).toEqual(TITLES);
    expect(EXAMPLES.map((e) => e.id)).toEqual(EXAMPLE_CONFIGS.map((c) => c.id));
    expect(new Set(EXAMPLES.map((e) => e.id)).size).toBe(EXAMPLES.length);
  });

  it("is exactly what catalog.generated.ts holds (run npm run examples:sync after changing a fixture or the config)", () => {
    const fresh = renderCatalog(buildExamples({ root: REPO_ROOT, target: readTarget() }));
    const onDisk = readFileSync(join(REPO_ROOT, "features/playground/examples/catalog.generated.ts"), "utf8");
    expect(onDisk).toBe(fresh);
    expect(onDisk.startsWith("// generated by npm run examples:sync; do not edit")).toBe(true);
  });

  it("each example's simulated stdout, stderr and exit code equal one recorded outcome", () => {
    for (const example of EXAMPLES) {
      const sim = SIMULATOR.run(example.source, example.lang);
      expect(sim.stop, example.id).toBeUndefined();
      const matches = recorded(example.fixture).outcomes.some(
        (o) => o.stdout === sim.stdout && o.stderr === sim.stderr && o.exitCode === sim.exitCode,
      );
      expect(matches, `${example.id}: simulated output matches no recorded outcome`).toBe(true);
    }
  });

  it("every example is verified against the pinned runtime, from a real recording", () => {
    const target = readTarget();
    for (const example of EXAMPLES) {
      expect(example.verified, example.id).toEqual({ node: target.node, v8: target.v8 });
    }
  });

  it("only the setImmediate example is nondeterministic", () => {
    const flagged = EXAMPLES.filter((e) => e.nondeterministic).map((e) => e.title);
    expect(flagged).toEqual(["setTimeout 0 vs setImmediate (nondeterministic!)"]);
  });

  it("an expectation recorded on a different Node than docs/TARGET.md is not verified", () => {
    const target = readTarget();
    const stale = buildExamples({ root: REPO_ROOT, target: { node: "0.0.0-test", v8: target.v8 } });
    expect(stale).toHaveLength(EXAMPLES.length);
    for (const example of stale) expect(example.verified, example.id).toBeNull();
    const staleV8 = buildExamples({ root: REPO_ROOT, target: { node: target.node, v8: "0.0.0-test" } });
    for (const example of staleV8) expect(example.verified, example.id).toBeNull();
  });

  it("fails when a configured fixture is missing", () => {
    expect(() =>
      buildExamples({
        root: REPO_ROOT,
        target: readTarget(),
        configs: [{ id: "ghost", title: "Ghost", fixture: "no-such-fixture", blurb: "never recorded" }],
      }),
    ).toThrow(/no-such-fixture/);
  });

  it("exampleForSource is an exact byte match", () => {
    const first = EXAMPLES[0];
    expect(first).toBeDefined();
    if (!first) return;
    expect(exampleForSource(first.source)).toBe(first);
    expect(exampleForSource(first.source + " ")).toBeNull();
    expect(exampleForSource(first.source.replace(/\n$/, ""))).toBeNull();
    expect(exampleForSource("")).toBeNull();
  });
});
